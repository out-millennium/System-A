export default function SystemAPolicyDocument() {
  const { locale } = useI18n();
  const russian = locale === "ru";
  const sourceLocale = locale === "fr" || locale === "zh" ? locale : "en";
  const translated = SYSTEM_POLICY_TRANSLATIONS[sourceLocale];
  const blocks = translated.split(/\n\s*\n/).map((block) => block.trim()).filter(Boolean);

  return (
    <article className="sa-policy-document">
      {!russian && locale === "es" && (
        <div className="mb-8 rounded-[var(--sa-r-md)] border border-[var(--sa-line-strong)] bg-[var(--sa-surface-1)] p-5 text-sm text-[var(--sa-text-secondary)]">
          Spanish translation fallback: English text is displayed until the Spanish version is published.
        </div>
      )}
      <header className="mb-10 border-b border-[var(--sa-line)] pb-8">
        <p className="sa-eyebrow">System A</p>
        <h1 className="sa-heading sa-text-gradient mt-4 text-3xl sm:text-5xl">
          {russian ? "ПОЛИТИКА ИСПОЛЬЗОВАНИЯ SYSTEM A" : blocks[0].replace(/\*\*/g, "")}
        </h1>
        <p className="mt-4 text-sm italic text-[var(--sa-text-tertiary)]">
          {russian
            ? "Пользовательский документ; не заменяет декларативные документы System A 01–10."
            : blocks[1]}
        </p>
      </header>
      {russian ? RU_SECTIONS.map(([title, paragraphs]) => (
        <section key={title} className="mb-9">
          <h2 className="sa-heading text-xl text-[var(--sa-text)]">{title}</h2>
          <div className="mt-4 space-y-3 text-sm leading-7 text-[var(--sa-text-secondary)]">
            {paragraphs.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}
          </div>
        </section>
      )) : blocks.slice(2).map((block) => {
        const text = block.replace(/\*\*/g, "");
        const heading = /^\d+\.\s/.test(text);
        return heading ? (
          <h2 key={block} className="sa-heading mb-4 mt-9 text-xl text-[var(--sa-text)]">{text}</h2>
        ) : (
          <p key={block} className="mb-3 text-sm leading-7 text-[var(--sa-text-secondary)]">{text}</p>
        );
      })}
    </article>
  );
}
